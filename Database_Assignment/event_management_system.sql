-- Q1: Event Popularity (Total Registrations)
SELECT 
    E.event_name,
    COUNT(R.registration_id) AS total_registrations
FROM Events E
JOIN Registrations R ON E.event_id = R.event_id
GROUP BY E.event_name
ORDER BY total_registrations DESC;

-- Q2: Total Registrations and Average Feedback for Each Event
SELECT 
    E.event_name,
    COUNT(R.registration_id) AS total_registrations,
    ROUND(AVG(R.feedback_rating), 2) AS average_rating
FROM Events E
LEFT JOIN Registrations R ON E.event_id = R.event_id
GROUP BY E.event_name
ORDER BY average_rating DESC NULLS LAST;

-- Q3: Find events with an average rating greater than 8
SELECT 
    E.event_name,
    ROUND(AVG(R.feedback_rating), 2) AS average_rating
FROM Events E
JOIN Registrations R ON E.event_id = R.event_id
WHERE R.feedback_rating IS NOT NULL
GROUP BY E.event_name
HAVING AVG(R.feedback_rating) > 8
ORDER BY average_rating DESC;

-- Q4: Determine total revenue generated by each event
SELECT 
    E.event_name,
    (COUNT(R.registration_id) * E.ticket_price) AS total_revenue
FROM Events E
JOIN Registrations R ON E.event_id = R.event_id
GROUP BY E.event_name, E.ticket_price
ORDER BY total_revenue DESC;

-- Q5: Identify top-performing events in each category (based on Average Rating)
WITH CategoryRatings AS (
    SELECT
        E.event_name,
        E.category,
        ROUND(AVG(R.feedback_rating), 2) AS average_rating,
        ROW_NUMBER() OVER (PARTITION BY E.category ORDER BY AVG(R.feedback_rating) DESC) AS rn
    FROM Events E
    JOIN Registrations R ON E.event_id = R.event_id
    WHERE R.feedback_rating IS NOT NULL
    GROUP BY E.event_name, E.category
)
SELECT 
    event_name,
    category,
    average_rating
FROM CategoryRatings
WHERE rn = 1;

-- Q6: Display users who attended more than one event
SELECT 
    U.name,
    COUNT(R.registration_id) AS events_attended
FROM Users U
JOIN Registrations R ON U.user_id = R.user_id
WHERE R.attended = TRUE
GROUP BY U.name
HAVING COUNT(R.registration_id) > 1
ORDER BY events_attended DESC;

-- Q7: Show users who have not attended any event
SELECT 
    U.name
FROM Users U
LEFT JOIN Registrations R ON U.user_id = R.user_id
GROUP BY U.user_id, U.name
HAVING SUM(CASE WHEN R.attended = TRUE THEN 1 ELSE 0 END) = 0;

-- Q8: Retrieve users who attended the most expensive event
SELECT 
    U.name,
    E.event_name
FROM Users U
JOIN Registrations R ON U.user_id = R.user_id
JOIN Events E ON R.event_id = E.event_id
WHERE R.attended = TRUE
  AND E.ticket_price = (SELECT MAX(ticket_price) FROM Events);

-- Q9: Generate a leaderboard showing each user’s total attended events and average rating
SELECT
    U.name,
    COUNT(CASE WHEN R.attended = TRUE THEN 1 END) AS total_attended_events,
    ROUND(AVG(CASE WHEN R.attended = TRUE THEN R.feedback_rating END), 2) AS average_rating_attended
FROM Users U
LEFT JOIN Registrations R ON U.user_id = R.user_id
GROUP BY U.name
ORDER BY total_attended_events DESC, average_rating_attended DESC NULLS LAST;
