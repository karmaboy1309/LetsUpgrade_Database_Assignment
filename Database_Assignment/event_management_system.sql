    role_name VARCHAR(50) UNIQUE NOT NULL
);
ALTER TABLE Users
ADD COLUMN role_id INT,
ADD FOREIGN KEY (role_id) REFERENCES UserRoles(role_id);



CREATE OR REPLACE VIEW RoleWiseUserSummary AS
SELECT
    ur.role_name,
    COUNT(u.user_id) AS total_users
FROM UserRoles ur
LEFT JOIN Users u ON ur.role_id = u.role_id
GROUP BY ur.role_name;


ALTER TABLE Users
ALTER city SET DEFAULT 'Unknown';

CREATE INDEX idx_events_ticket_price
ON Events(ticket_price);

CREATE OR REPLACE VIEW EventCategoryCountView AS
SELECT
    category,
    COUNT(event_id) AS total_events
FROM Events
GROUP BY category;

ALTER TABLE Events
ADD COLUMN created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;

CREATE OR REPLACE VIEW RecentEventsView AS
SELECT
    event_id,
    event_name,
    category,
    ticket_price,
    created_at
FROM Events
ORDER BY created_at DESC;

ALTER TABLE Users
ADD COLUMN email VARCHAR(150) UNIQUE;
CREATE OR REPLACE VIEW UserContactDirectory AS
SELECT
    name,
    email,
    city
FROM Users
WHERE email IS NOT NULL;


ALTER TABLE Events
ADD CONSTRAINT chk_ticket_price_positive CHECK (ticket_price >= 0);
